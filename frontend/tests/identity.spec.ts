import { expect, test } from "@playwright/test";

test.describe.configure({ mode: "serial" });

test("sesión, estudiantes, contexto institucional y archivo", async ({ page, context }, info) => {
  test.skip(process.env.E2E_IDENTITY !== "1", "Requiere el entorno aislado y el fixture E2E");
  await page.goto("/");
  await page.getByLabel("Correo electrónico").fill(`${info.project.name}@example.com`);
  await page.getByLabel("Contraseña", { exact: true }).fill("Ficticia-E2E-2026");
  await page.getByRole("button", { name: "Iniciar sesión" }).click();
  await expect(page.getByRole("heading", { name: "Estudiantes", exact: true })).toBeVisible();
  const cookie = (await context.cookies()).find(item => item.name === "ea_session");
  expect(cookie?.httpOnly).toBe(true);
  expect(cookie?.sameSite).toBe("Lax");
  const student = `Estudiante ficticio ${Date.now()}`;
  await page.getByRole("button", { name: "Crear estudiante", exact: true }).click();
  await page.getByLabel("Nombre completo").fill(student);
  await page.getByLabel("Código del estudiante").fill(`TEST-${Date.now()}`);
  await page.getByRole("button", { name: "Guardar", exact: true }).click();
  await expect(page.getByRole("cell", { name: student, exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("cell", { name: student, exact: true })).toBeVisible();
  const select = page.getByRole("combobox", { name: "Institución", exact: true });
  await select.selectOption({ label: `Segundo centro ${info.project.name}` });
  await expect(page.getByRole("cell", { name: student, exact: true })).toHaveCount(0);
  await expect(page.getByText("Todavía no hay estudiantes")).toBeVisible();
  await select.selectOption({ label: `Centro ficticio ${info.project.name}` });
  const row = page.getByRole("row").filter({ has: page.getByRole("cell", { name: student, exact: true }) });
  await row.getByRole("button", { name: "Editar" }).click();
  await page.getByLabel("Nombre completo").fill(student + " corregido");
  await page.getByRole("button", { name: "Guardar", exact: true }).click();
  const updated = page.getByRole("row").filter({ has: page.getByRole("cell", { name: student + " corregido", exact: true }) });
  page.once("dialog", dialog => dialog.accept());
  await updated.getByRole("button", { name: "Archivar" }).click();
  await expect(updated.getByText("Archivado", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([]);
  await page.screenshot({ path: info.outputPath("gestion-estudiantes.png"), fullPage: true });
  await page.getByRole("button", { name: "Cerrar sesión" }).click();
  await expect(page.getByRole("button", { name: "Iniciar sesión" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "Iniciar sesión" })).toBeVisible();
});

test("estructura, matrícula y acceso del docente asignado", async ({ page, browser }, info) => {
  test.skip(process.env.E2E_IDENTITY !== "1", "Requiere el entorno aislado y el fixture E2E");
  const suffix = `${info.project.name}-${Date.now()}`;
  await page.goto("/");
  await page.getByLabel("Correo electrónico").fill(`${info.project.name}@example.com`);
  await page.getByLabel("Contraseña", { exact: true }).fill("Ficticia-E2E-2026");
  await page.getByRole("button", { name: "Iniciar sesión" }).click();
  await expect(page.getByRole("heading", { name: "Estudiantes", exact: true })).toBeVisible();
  const begin = new Date(); begin.setDate(begin.getDate() - 2);
  const end = new Date(); end.setFullYear(end.getFullYear() + 1);
  async function open(tab: string, create: string) {
    await page.getByRole("navigation").getByRole("button", { name: tab, exact: true }).click();
    await page.getByRole("button", { name: create, exact: true }).click();
  }
  async function save() {
    await page.getByRole("button", { name: "Guardar", exact: true }).click();
    await expect(page.getByText("Registro guardado.", { exact: true })).toBeVisible();
  }
  await open("Años escolares", "Crear año escolar");
  await page.getByLabel("Nombre", { exact: true }).fill(`Año ${suffix}`);
  await page.getByLabel("Fecha inicial").fill(begin.toISOString().slice(0, 10));
  await page.getByLabel("Fecha final").fill(end.toISOString().slice(0, 10));
  await save();
  await open("Cursos", "Crear curso");
  await page.getByLabel("Nombre", { exact: true }).fill(`Curso ${suffix}`);
  await page.getByLabel("Grado", { exact: true }).fill("1");
  await save();
  await open("Secciones", "Crear sección");
  await page.getByLabel("Nombre", { exact: true }).fill(`Sección ${suffix}`);
  await page.getByRole("combobox", { name: "Curso", exact: true }).selectOption({ label: `Curso ${suffix}` });
  await page.getByRole("combobox", { name: "Año escolar", exact: true }).selectOption({ label: `Año ${suffix}` });
  await save();
  await open("Estudiantes", "Crear estudiante");
  await page.getByLabel("Nombre completo").fill(`Alumno ${suffix}`);
  await save();
  await open("Matrículas", "Crear matrícula");
  await page.getByRole("combobox", { name: "Estudiante", exact: true }).selectOption({ label: `Alumno ${suffix}` });
  await page.getByRole("combobox", { name: "Sección", exact: true }).selectOption({ label: `Sección ${suffix}` });
  await page.getByLabel("Fecha inicial").fill(begin.toISOString().slice(0, 10));
  await save();
  await open("Equipo y permisos", "Crear miembro");
  await page.getByLabel("Nombre completo").fill(`Docente ${suffix}`);
  await page.getByLabel("Correo electrónico").fill(`docente-${suffix}@example.com`);
  await page.getByRole("combobox", { name: "Rol", exact: true }).selectOption("TEACHER");
  await page.getByLabel("Contraseña inicial").fill("Ficticia-E2E-2026");
  await save();
  await open("Asignaciones docentes", "Crear asignación docente");
  await page.getByRole("combobox", { name: "Docente", exact: true }).selectOption({ label: `Docente ${suffix}` });
  await page.getByRole("combobox", { name: "Sección", exact: true }).selectOption({ label: `Sección ${suffix}` });
  await page.getByRole("combobox", { name: "Año escolar", exact: true }).selectOption({ label: `Año ${suffix}` });
  await page.getByLabel("Asignatura", { exact: true }).fill("Lengua");
  await save();
  const teacher = await browser.newContext();
  const teacherPage = await teacher.newPage();
  await teacherPage.goto(info.project.use.baseURL ?? process.env.E2E_BASE_URL ?? "http://127.0.0.1:3101");
  await teacherPage.getByLabel("Correo electrónico").fill(`docente-${suffix}@example.com`);
  await teacherPage.getByLabel("Contraseña", { exact: true }).fill("Ficticia-E2E-2026");
  await teacherPage.getByRole("button", { name: "Iniciar sesión" }).click();
  await expect(teacherPage.getByRole("cell", { name: `Alumno ${suffix}`, exact: true })).toBeVisible();
  await expect(teacherPage.getByRole("button", { name: "Crear estudiante" })).toHaveCount(0);
  await teacher.close();
  await page.getByRole("button", { name: "Gestionar institución", exact: true }).click();
  await page.getByRole("combobox", { name: "Operación", exact: true }).selectOption("create");
  await page.getByLabel("Nombre de la institución").fill(`Nuevo centro ${suffix}`);
  await page.getByRole("button", { name: "Guardar institución", exact: true }).click();
  await page.getByRole("combobox", { name: "Institución", exact: true }).selectOption({ label: `Nuevo centro ${suffix}` });
  await page.getByRole("navigation").getByRole("button", { name: "Estudiantes", exact: true }).click();
  await expect(page.getByText("Todavía no hay estudiantes")).toBeVisible();
});
